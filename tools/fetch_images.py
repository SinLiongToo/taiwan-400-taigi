# -*- coding: utf-8 -*-
"""Download the historical pictures shown under the films from Wikimedia Commons.

Reads tools/pictures.json, saves images/<key>.jpg (900 px wide at most) and writes pictures.js:
  window.PICTURES = { main: [...], c228: [...], cwt: [...] }
Each entry carries the caption, the time it starts showing, and the file's author, licence and
Commons page so the page can credit it. Files that are missing or not freely licensed are skipped.

  python tools/fetch_images.py            # download what is missing, rewrite pictures.js
  python tools/fetch_images.py --force    # download everything again
"""
import io, json, re, sys, time, urllib.parse, urllib.request
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "tools" / "pictures.json"
CACHE = ROOT / "tools" / "pictures_cache.json"
OUT = ROOT / "images"
UA = {"User-Agent": "history-page-image-fetcher/1.0 (educational static site)"}
API = "https://commons.wikimedia.org/w/api.php"
WIDTH = 900


def get(url):
    for i in range(6):
        try:
            return urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60).read()
        except Exception as e:
            if i == 5:
                raise
            time.sleep(20 * (i + 1))


def strip(html):
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", html or "")).strip()


def main():
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass
    force = "--force" in sys.argv
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    cache = json.loads(CACHE.read_text(encoding="utf-8")) if CACHE.exists() else {}
    OUT.mkdir(exist_ok=True)
    result = {}
    for group, items in spec.items():
        if group.startswith("_"):
            continue
        result[group] = []
        for it in items:
            key, dest = it["key"], OUT / f"{it['key']}.jpg"
            meta = cache.get(key)
            if force or not dest.exists() or not meta or meta.get("file") != it["file"]:
                q = urllib.parse.urlencode({"action": "query", "prop": "imageinfo", "titles": "File:" + it["file"],
                                            "iiprop": "url|extmetadata", "iiurlwidth": WIDTH, "format": "json", "formatversion": "2"})
                page = json.loads(get(API + "?" + q))["query"]["pages"][0]
                if page.get("missing") or "imageinfo" not in page:
                    print("MISSING ", key, it["file"]); continue
                info = page["imageinfo"][0]; md = info.get("extmetadata", {})
                if md.get("NonFree", {}).get("value") in ("true", True):
                    print("NON-FREE", key, it["file"]); continue
                img = Image.open(io.BytesIO(get(info["thumburl"]))).convert("RGB")
                img.save(dest, "JPEG", quality=80, optimize=True, progressive=True)
                meta = {"file": it["file"], "w": img.width, "h": img.height,
                        "license": strip(md.get("LicenseShortName", {}).get("value", "")),
                        "artist": strip(md.get("Artist", {}).get("value", ""))[:90],
                        "url": info.get("descriptionurl", "")}
                cache[key] = meta
                CACHE.write_text(json.dumps(cache, ensure_ascii=False, indent=1), encoding="utf-8")
                print("ok      ", key, "|", meta["license"], "|", meta["artist"][:40], flush=True)
                time.sleep(3)
            result[group].append({"t": it["t"], "key": key, "zh": it["zh"], "en": it["en"], "w": meta["w"], "h": meta["h"],
                                  "license": meta["license"], "artist": meta["artist"], "url": meta["url"]})
        result[group].sort(key=lambda x: x["t"])
    (ROOT / "pictures.js").write_text("// Generated by tools/fetch_images.py from tools/pictures.json. Do not edit by hand.\n"
                                      "window.PICTURES = " + json.dumps(result, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
    print("wrote pictures.js:", {g: len(v) for g, v in result.items()})


if __name__ == "__main__":
    main()
